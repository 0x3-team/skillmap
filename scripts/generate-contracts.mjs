#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const manifestPath = path.join(repo, "contracts/manifest.json");
const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
const schemas = [];

for (const entry of manifest.schemas) {
  const schema = JSON.parse(await readFile(path.join(repo, "contracts", entry.path), "utf8"));
  if (schema.$id !== entry.id) {
    throw new Error(`Contract manifest ID mismatch for ${entry.path}: ${schema.$id} !== ${entry.id}`);
  }
  schemas.push(schema);
}

const source = `// Generated by scripts/generate-contracts.mjs. Do not edit by hand.\n` +
  `export const CONTRACT_SCHEMAS = ${JSON.stringify(schemas, null, 2)} as const;\n\n` +
  `export type ContractSchema = (typeof CONTRACT_SCHEMAS)[number];\n` +
  `export type ContractSchemaId = ContractSchema[\"$id\"];\n` +
  `export const CONTRACT_SCHEMA_IDS = CONTRACT_SCHEMAS.map((schema) => schema.$id) as readonly ContractSchemaId[];\n`;
const typeTemplatePath = path.join(repo, "contracts/type-facade.ts");
const typeTemplate = await readFile(typeTemplatePath, "utf8");
const typeSource = `// Generated by scripts/generate-contracts.mjs from contracts/type-facade.ts. Do not edit by hand.\n` +
  typeTemplate.replace(/^\/\/ Source template[^\n]*\n/, "");
const rootValidatorPath = path.join(repo, "src/contracts/validate.ts");
const rootValidator = await readFile(rootValidatorPath, "utf8");
const evalSemanticsPath = path.join(repo, "src/contracts/eval-semantics.ts");
const evalSemantics = await readFile(evalSemanticsPath, "utf8");
const routeRankingPath = path.join(repo, "src/contracts/route-ranking.ts");
const routeRanking = await readFile(routeRankingPath, "utf8");
const fixturePathPath = path.join(repo, "src/contracts/fixture-path.ts");
const fixturePath = await readFile(fixturePathPath, "utf8");
const webValidatorSource = `// Generated by scripts/generate-contracts.mjs from src/contracts/validate.ts. Do not edit by hand.\n` +
  rootValidator
    .replace("'./generated/schema-bundle.js'", "'./schema-bundle.js'")
    .replace("'./generated/types.js'", "'./types.js'");
const webEvalSemanticsSource = `// Generated by scripts/generate-contracts.mjs from src/contracts/eval-semantics.ts. Do not edit by hand.\n${evalSemantics}`;
const webRouteRankingSource = `// Generated by scripts/generate-contracts.mjs from src/contracts/route-ranking.ts. Do not edit by hand.\n${routeRanking}`;
const webFixturePathSource = `// Generated by scripts/generate-contracts.mjs from src/contracts/fixture-path.ts. Do not edit by hand.\n${fixturePath}`;

const targets = [
  path.join(repo, "src/contracts/generated/schema-bundle.ts"),
  path.join(repo, "apps/web/lib/contracts/generated/schema-bundle.ts")
];
const typeTargets = [
  path.join(repo, "src/contracts/generated/types.ts"),
  path.join(repo, "apps/web/lib/contracts/generated/types.ts")
];
const webValidatorTarget = path.join(repo, "apps/web/lib/contracts/generated/validate.server.ts");
const webEvalSemanticsTarget = path.join(repo, "apps/web/lib/contracts/generated/eval-semantics.ts");
const webRouteRankingTarget = path.join(repo, "apps/web/lib/contracts/generated/route-ranking.ts");
const webFixturePathTarget = path.join(repo, "apps/web/lib/contracts/generated/fixture-path.ts");
const check = process.argv.includes("--check");
const stale = [];

for (const target of targets) {
  if (check) {
    const current = await readFile(target, "utf8").catch(() => "");
    if (current !== source) stale.push(path.relative(repo, target));
  } else {
    await writeFile(target, source, "utf8");
  }
}

for (const target of typeTargets) {
  if (check) {
    const current = await readFile(target, "utf8").catch(() => "");
    if (current !== typeSource) stale.push(path.relative(repo, target));
  } else {
    await writeFile(target, typeSource, "utf8");
  }
}

if (check) {
  const current = await readFile(webValidatorTarget, "utf8").catch(() => "");
  if (current !== webValidatorSource) stale.push(path.relative(repo, webValidatorTarget));
  const currentEvalSemantics = await readFile(webEvalSemanticsTarget, "utf8").catch(() => "");
  if (currentEvalSemantics !== webEvalSemanticsSource) stale.push(path.relative(repo, webEvalSemanticsTarget));
  const currentRouteRanking = await readFile(webRouteRankingTarget, "utf8").catch(() => "");
  if (currentRouteRanking !== webRouteRankingSource) stale.push(path.relative(repo, webRouteRankingTarget));
  const currentFixturePath = await readFile(webFixturePathTarget, "utf8").catch(() => "");
  if (currentFixturePath !== webFixturePathSource) stale.push(path.relative(repo, webFixturePathTarget));
} else {
  await writeFile(webValidatorTarget, webValidatorSource, "utf8");
  await writeFile(webEvalSemanticsTarget, webEvalSemanticsSource, "utf8");
  await writeFile(webRouteRankingTarget, webRouteRankingSource, "utf8");
  await writeFile(webFixturePathTarget, webFixturePathSource, "utf8");
}

if (stale.length > 0) {
  throw new Error(`Generated contract bundles are stale: ${stale.join(", ")}. Run node scripts/generate-contracts.mjs.`);
}

if (!check) {
  process.stdout.write(`Generated ${schemas.length} schemas, contract type facades, and the web validator modules.\n`);
}
