import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';
import {
  normalizeRouteRankingLimit,
  rankRoutePrompt,
  validateRoutePrompt
} from '../dist/contracts/route-ranking.js';
import { routePrompt, routeSemanticDecision } from '../dist/core/route.js';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function rankingSkill(index, overrides = {}) {
  const name = ['alpha', 'bravo', 'charlie', 'delta', 'echo'][index] ?? `skill-${index}`;
  return {
    skillId: `sk_${String(index).padStart(43, 'A')}`,
    name,
    description: 'Shared route work',
    tier: 'active-default',
    family: undefined,
    path: `/private/${name}`,
    aliases: [],
    preferredFor: ['shared route work'],
    avoidFor: [],
    supersedes: [],
    routeEligible: true,
    qualifiedExplicitAllowed: true,
    variantState: 'unique',
    hasScripts: false,
    ...overrides
  };
}

test('canonical and generated web route-ranking modules remain converged', async () => {
  const canonical = await readFile(path.join(repo, 'src/contracts/route-ranking.ts'), 'utf8');
  const generated = await readFile(path.join(repo, 'apps/web/lib/contracts/generated/route-ranking.ts'), 'utf8');
  assert.equal(
    generated,
    `// Generated by scripts/generate-contracts.mjs from src/contracts/route-ranking.ts. Do not edit by hand.\n${canonical}`
  );
});

test('pure route ranking preserves the routePrompt recommendations, exclusions, and legacy hook text', () => {
  const skills = [
    rankingSkill(0, { supersedes: ['bravo'] }),
    rankingSkill(1),
    rankingSkill(2, { tier: 'blocked', routeEligible: false }),
    rankingSkill(3, { tier: 'explicit-only' })
  ];
  const prompt = 'Handle shared route work with alpha';
  const ranked = rankRoutePrompt(skills, prompt, 3);
  const routed = routePrompt({ skills }, prompt, 3);
  const domain = routeSemanticDecision({ skills }, prompt, 3);
  assert.deepEqual(routed.recommendations, ranked.recommendations);
  assert.deepEqual(routed.exclusions, ranked.exclusions);
  assert.equal(routed.hookText, ranked.hookText);
  assert.equal(domain.hookText, ranked.hookText, 'domain/API routing must use the exact evaluated advisory text');
  assert.deepEqual(ranked.recommendations.map((item) => item.name), ['alpha']);
  assert.equal(ranked.exclusions.some((item) => item.name === 'bravo' && item.reason === 'superseded by alpha'), true);
  assert.equal(ranked.exclusions.some((item) => item.name === 'charlie' && item.reason === 'tier=blocked'), true);
  assert.equal(ranked.exclusions.some((item) => item.name === 'delta' && item.reason === 'explicit-only and not named in prompt'), true);
  assert.equal(ranked.hookText, `SkillMap: prefer alpha. Avoid superseded: ${skills[1].skillId}.`);
});

test('pure route ranking preserves exact default max=3 and limit normalization semantics', () => {
  const skills = Array.from({ length: 4 }, (_, index) => rankingSkill(index));
  const prompt = 'Handle shared route work';
  assert.deepEqual(rankRoutePrompt(skills, prompt).recommendations.map((item) => item.name), ['alpha', 'bravo', 'charlie']);
  assert.deepEqual(rankRoutePrompt(skills, prompt, 3.9).recommendations.map((item) => item.name), ['alpha', 'bravo', 'charlie']);
  assert.deepEqual(rankRoutePrompt(skills, prompt, 4).recommendations.map((item) => item.name), ['alpha', 'bravo', 'charlie', 'delta']);
  assert.equal(normalizeRouteRankingLimit(3.9), 3);
  assert.throws(() => normalizeRouteRankingLimit(0), /integer between 1 and 10/);
  assert.throws(() => normalizeRouteRankingLimit(11), /integer between 1 and 10/);
  assert.throws(() => normalizeRouteRankingLimit(Number.POSITIVE_INFINITY), /finite number between 1 and 10/);
});

test('runtime and eval replay share the exact UTF-8 prompt admission boundary', () => {
  assert.equal(validateRoutePrompt('route this work'), 'route this work');
  assert.equal(validateRoutePrompt('   ', true), '   ', 'a qualified invocation may omit natural-language prompt text');
  assert.throws(() => validateRoutePrompt('   '), /must not be empty/);
  assert.throws(() => validateRoutePrompt('route\u0000this'), /forbidden NUL byte/);
  assert.throws(() => validateRoutePrompt('😀'.repeat(9000)), /32768-byte limit/);
});

test('qualified explicit routing admits only the exact approved skill identity', () => {
  const qualifiedOnly = rankingSkill(0, {
    routeEligible: false,
    qualifiedExplicitAllowed: true,
    variantState: 'shadowed-duplicate'
  });
  const implicit = rankRoutePrompt([qualifiedOnly], 'handle alpha work', 3);
  assert.deepEqual(implicit.recommendations, []);
  assert.equal(implicit.exclusions[0]?.reason, 'variant=shadowed-duplicate; implicit routing disabled');

  const highScoringRival = rankingSkill(1, {
    aliases: Array.from({ length: 21 }, () => 'rival-match'),
    supersedes: ['alpha']
  });
  const explicit = rankRoutePrompt([qualifiedOnly, highScoringRival], 'rival-match', 1, qualifiedOnly.skillId);
  assert.deepEqual(explicit.recommendations.map((item) => item.skillId), [qualifiedOnly.skillId]);
  assert.throws(
    () => rankRoutePrompt([qualifiedOnly], '', 3, 'sk_ZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZ'),
    /not present in the effective registry/
  );

  const blockedQualified = rankingSkill(1, {
    routeEligible: false,
    qualifiedExplicitAllowed: false,
    variantState: 'unresolved-duplicate'
  });
  const blocked = rankRoutePrompt([blockedQualified], '', 3, blockedQualified.skillId);
  assert.deepEqual(blocked.recommendations, []);
  assert.equal(blocked.exclusions[0]?.reason, 'qualified invocation is blocked by policy or frontmatter');
});

test('implicit phrase scoring uses token boundaries consistent with leakage checks', () => {
  const shortName = rankingSkill(0, {
    name: 'go',
    description: 'Specialized runtime',
    preferredFor: [],
    aliases: []
  });
  const result = rankRoutePrompt([shortName], 'Review a google deployment', 3);
  assert.deepEqual(result.recommendations, []);
  assert.deepEqual(rankRoutePrompt([shortName], 'Review an égoé deployment', 3).recommendations, []);
  assert.deepEqual(rankRoutePrompt([shortName], 'Review a 技能go技能 deployment', 3).recommendations, []);
});
